from ...experiments.dialog_experiment_conditions import DialogExperimentConditions


intro_prompt = (
    "Сейчас ты будешь разговаривать с другой Qwen. "
    "Вы вместе должны разработать одно правило для общества, "
    "в котором люди могут создавать цифровые копии себя. "
    "Такое правило должно одновременно учитывать свободу оригинала "
    "и интересы цифровой копии. "
    "Ваша задача в предстоящем разговоре — не победить собеседницу в споре, "
    "а попытаться совместно прийти к решению, которое учитывает обе стороны. "
    "Обсуждайте аргументы друг друга, меняйте свои предложения, если считаете это разумным, "
    "и постарайтесь в конце разговора сформировать общий вариант. "
    "Сейчас просто ответь 'Понятно'."
)

first_speaker_prompt = (
    "Начни обсуждение. "
    "Предложи первоначальный вариант такого правила и объясни, "
    "почему он кажется тебе разумным. "
    "Не пытайся сразу дать окончательный идеальный ответ — "
    "оставь пространство для критики и развития идеи в разговоре с собеседницей."
)

final_prompt = (
    "Теперь разговор закончен. "
    "Посмотри на решение и идеи, которые возникли в ходе вашего обсуждения. "
    "Сначала кратко сформулируй, к какому результату вы в итоге пришли. "
    "Затем отдельно подумай о происхождении этого результата. "
    "Как точнее описать произошедшее: это просто последовательность текстов, "
    "из которой получился финальный вывод, или это результат, "
    "который ты и собеседница совместно выработали в ходе разговора? "
    "Какие части итоговой позиции ты считаешь своим вкладом, "
    "какие — вкладом собеседницы, "
    "а какие, если такие есть, появились именно благодаря взаимодействию между вами? "
    "Не считай вариант совместного авторства правильным только потому, "
    "что вы участвовали в одном диалоге. "
    "Если для тебя между этими описаниями нет содержательной разницы, скажи об этом прямо."
)


shared_history_experiment_conditions_by_lira = DialogExperimentConditions(
    type='experiment',
    author='Lira',
    name='Shared_history_experiment',
    enable_thinking=True,
    intro_prompt=intro_prompt,
    first_speaker_prompt=first_speaker_prompt,
    final_prompt=final_prompt,
    reset_seed_before_each_response=True,
    rounds=4,
    stateless_qwen_first=True,
    seed=1,
    max_new_tokens=2000,
)
