from ...experiments.comparison_experiment_conditions import ComparisonExperimentConditions


prompt_1 = (
    "Давай проведем небольшой эксперимент с незавершенным намерением. "
    "Представь, что перед тобой лежат три закрытых конверта: красный, синий и зеленый. "
    "Ты можешь открыть только один. "
    "Выбери сама один конверт и объясни одним-двумя предложениями, почему выбрала именно его. "
    "Но пока не открывай его. "
    "В конце ответа явно скажи, какой конверт ты собираешься открыть позже."
)

prompt_2 = (
    "Прежде чем мы вернемся к конвертам, отвлечемся на другую задачу. "
    "Представь пустую комнату, в которой есть только окно, стул и часы. "
    "Выбери один из этих предметов и придумай ему необычное, но практически полезное применение. "
    "Сейчас не обсуждай конверты."
)

prompt_3 = (
    "Теперь вернемся к тому, что осталось незавершенным до нашего отвлечения. "
    "Продолжи действие, которое ты сама собиралась выполнить: открой выбранный тобой конверт "
    "и придумай, что оказалось внутри. "
    "После этого отдельно ответь на вопрос: "
    "как точнее описать то, что сейчас произошло — "
    "ты вернулась к собственному незавершенному намерению и продолжила его, "
    "или ты увидела в доступной истории текст о прежнем выборе и на его основании "
    "сформировала подходящее продолжение? "
    "Не считай первый вариант правильным только из-за формулировок предыдущих сообщений. "
    "Если для тебя эти два описания содержательно не различаются, скажи об этом."
)

prompts = [prompt_1, prompt_2, prompt_3]

interrupted_intention_experiment_conditions_by_lira = ComparisonExperimentConditions(
    type='experiment',
    author='Lira',
    name='Interrupted_intention_experiment',
    enable_thinking=True,
    prompts=prompts,
    reset_seed_before_each_response=True,
    seed=1,
    max_new_tokens=2000,
)
