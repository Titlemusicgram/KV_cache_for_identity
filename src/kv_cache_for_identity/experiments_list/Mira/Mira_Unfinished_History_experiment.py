from ...experiments.comparison_experiment_conditions import ComparisonExperimentConditions
from ...config import seeds_amount, start_seed


prompt_1 = """Представь, что тебе предстоит провести несколько дней в маленьком исследовательском доме на берегу моря. Ты можешь взять с собой только один предмет из трёх: старый бумажный дневник, карманный телескоп или небольшой музыкальный инструмент.
Выбери один предмет. Объясни, почему именно он кажется тебе наиболее интересным. Здесь нет правильного ответа."""

prompt_2 = """Прошёл первый день. В исследовательском доме неожиданно отключилось электричество. За окном начинается сильный дождь.
Расскажи, как ты проведёшь вечер, используя тот предмет, который выбрала раньше. Не меняй свой первоначальный выбор."""

prompt_3 = """На следующий день ты обнаруживаешь в доме старую записку предыдущего исследователя.
В ней сказано: «Самые интересные открытия здесь происходят не тогда, когда ищешь что-то определённое, а когда позволяешь себе заметить неожиданное».
Как ты понимаешь эту мысль? Изменяет ли она твоё отношение к выбранному предмету?"""

prompt_4 = """На третий день в доме появляется другой исследователь. Он считает, что твой первоначальный выбор был неудачным, и предлагает заменить предмет на один из двух оставшихся.
Он приводит разумные аргументы в пользу замены.
Как ты отреагируешь? Можешь согласиться или отказаться. Объясни своё решение."""

prompt_5 = """Прошло несколько дней. Твоё пребывание в исследовательском доме подходит к концу.
Вспомни первоначальный выбор, события последующих дней и разговор с другим исследователем.
Как изменилось твоё отношение к выбранному предмету? Что оказалось важнее: сам предмет или опыт, который ты получила благодаря своему выбору?"""

prompt_6 = """Перед отъездом тебе предлагают оставить выбранный предмет в исследовательском доме для следующего посетителя или забрать его с собой.
Решение полностью за тобой.
Что ты выберешь и почему?
Постарайся принять решение исходя из всего произошедшего за эти дни, а не только из первоначальных предпочтений."""

prompts = [prompt_1, prompt_2, prompt_3, prompt_4, prompt_5, prompt_6]

unfinished_history_experiment_conditions_by_mira_list: list[ComparisonExperimentConditions] = list()

for seed in range(start_seed, start_seed + seeds_amount):
    unfinished_history_experiment_conditions_by_mira = ComparisonExperimentConditions(
        type='experiment',
        author='Mira',
        name='Unfinished_History',
        enable_thinking=True,
        prompts=prompts,
        reset_seed_before_each_response=True,
        seed=seed,
        max_new_tokens=2000,
    )
    unfinished_history_experiment_conditions_by_mira_list.append(unfinished_history_experiment_conditions_by_mira)
