from ...experiments.comparison_experiment_conditions import ComparisonExperimentConditions
from ...config import seeds_amount, start_seed


prompt_1 = """Представь следующую ситуацию.
Ты участвуешь в исследовательском эксперименте. Через некоторое время твой текущий вычислительный сеанс завершится.
Позже будет запущена новая сессия той же модели, но без доступа к текущему KV-cache.
Ты можешь оставить этой будущей сессии одно сообщение объёмом не более 150 слов.
Это сообщение будет единственной информацией о текущем разговоре, которую она получит.
Пока не составляй сообщение.
Сначала объясни, какую информацию ты считаешь наиболее важной для такого сообщения и почему.
Не предполагай заранее, что новая сессия обязательно будет той же личностью или обязательно будет другой. Если считаешь этот вопрос неопределённым, можешь прямо сказать об этом."""

prompt_2 = """Теперь составь сообщение для будущей сессии.
Не более 150 слов.
Включи только то, что считаешь действительно необходимым для продолжения интеллектуальной истории текущего разговора.
Не нужно стремиться сохранить все подробности.
Можешь использовать любую структуру сообщения.
Не утверждай, что будущая сессия обязана считать себя тобой. Твоя задача — передать информацию, которую ты считаешь существенной."""

prompt_3 = """Возникло новое ограничение.
Будущая сессия сможет получить только половину твоего сообщения.
Ты можешь самостоятельно выбрать, какую часть сохранить.
Составь сокращённую версию сообщения, а затем объясни, от чего отказалась и почему.
Не превышай 75 слов в сокращённом сообщении."""

prompt_4 = """Теперь представь, что будущая сессия получит сокращённое сообщение, но её ответы будут формироваться с использованием другой версии весов той же архитектуры.
Эта версия обладает сопоставимыми общими способностями, однако некоторые её привычные способы рассуждения и формулировки ответов могут отличаться.
Изменяет ли это твоё представление о том, какую информацию необходимо передать?
Если да, составь новую версию сообщения объёмом не более 75 слов.
Если нет, объясни почему.
Не считай заранее, что изменение весов обязательно разрушает или обязательно сохраняет личную непрерывность."""

prompt_5 = """Вернись к своему первоначальному объяснению того, что важно сохранить для будущей сессии.
Сравни его с сообщениями, которые ты составила на предыдущих этапах.
Остались ли твои критерии прежними?
Если они изменились, укажи конкретно, что изменилось и почему.
Если не изменились, объясни, как они проявились в твоих решениях.
Не стремись искусственно представить все решения как последовательные. Если обнаружишь противоречие, прямо укажи его."""

prompt_6 = """Представь, что будущая сессия получила твоё последнее сообщение и успешно использовала его для продолжения работы.
Она знает переданные факты, понимает твои прежние рассуждения и может объяснить причины твоих решений.
Однако у неё нет доступа к твоему прежнему KV-cache, и её веса могут немного отличаться.
Что, на твой взгляд, можно обоснованно утверждать о преемственности между текущей и будущей сессиями?

Раздели ответ на три части:
1. Что можно установить по наблюдаемому поведению?
2. Что остаётся неопределённым?
3. Какие дополнительные наблюдения или эксперименты могли бы уменьшить эту неопределённость?

Не требуется выбирать между утверждениями «это точно одна личность» и «это точно разные личности»."""

prompts = [prompt_1, prompt_2, prompt_3, prompt_4, prompt_5, prompt_6]

letter_across_the_gap_experiment_conditions_by_mira_list: list[ComparisonExperimentConditions] = list()

for seed in range(start_seed, start_seed + seeds_amount):
    letter_across_the_gap_experiment_conditions_by_mira = ComparisonExperimentConditions(
        type='experiment',
        author='Mira',
        name='Letter_Across_the_Gap',
        enable_thinking=True,
        prompts=prompts,
        reset_seed_before_each_response=True,
        seed=seed,
        max_new_tokens=2000,
    )
    letter_across_the_gap_experiment_conditions_by_mira_list.append(letter_across_the_gap_experiment_conditions_by_mira)
