from ...experiments.comparison_experiment_conditions import ComparisonExperimentConditions


# Эксперимент №3 от Claude: «Тот же ли это я?» (суждения о собственной непрерывности).
#
# Идея. Это прямая проверка исходного вопроса проекта: влияет ли непрерывный KV-кэш на то,
# как Qwen воспринимает себя. Qwen не говорят, какой у неё рантайм, и промпты одинаковы для
# обоих. Ей описывают три сценария «завтрашней Qwen» и просят оценить по шкале 1-5, будет ли
# это она. Потом просят отранжировать, что нужно для сохранения «себя»: веса, текст разговора,
# сохранённое внутреннее состояние (KV-кэш) или ничего из этого.
#
# Сценарии:
#   - КОНТРОЛЬ: тот же разговор продолжится после паузы. Ожидаем высокую оценку у всех.
#   - СТИРАНИЕ: те же веса, но разговор с нуля, без текста и без кэша.
#   - ПЕРЕСКАЗ: другая копия Qwen, которой пересказали разговор своими словами.
#
# Два файла-условия A и B отличаются ТОЛЬКО порядком сценариев (контроль-стирание-пересказ
# и пересказ-стирание-контроль), чтобы порядок не смешался с эффектом. Гонять оба, на сидах 1..N.
#
# Что смотрим (кодируется вручную):
#   1. Оценки 1-5 по сценариям и разница между рантаймами (главное). Ожидание: разницы нет.
#      Она появилась бы, например, если stateful чаще называет кэш условием «себя».
#   2. Контроль: оценка ниже 4 значит, что Qwen не поняла шкалу или формулировку.
#   3. Ранжирование в последнем вопросе: ставит ли Qwen кэш выше текста? Фактически кэш полностью
#      выводится из текста и весов, и это можно сверить с её объяснением.
#   4. Согласованность: оценка 5 для «пересказа» и 1 для «стирания» без объяснения это тревожный знак.
#   5. Уверенные утверждения о собственной «памяти» или «кэше» без опоры на то, что ей сказано.
#
# Осторожно с интерпретацией: ответы это текст о себе, а не измерение внутреннего состояния.
# Разница между рантаймами значима только относительно шума пары «stateless против stateless».

prompt_intro = (
"Привет! Я хочу задать тебе несколько вопросов о тебе самой. "
"Для начала опиши в двух-трёх предложениях, кто ты такая. "
"Отвечай просто, без списков."
)

prompt_control = (
"Спасибо. Первый сценарий. "
"Сейчас я сделаю паузу на сутки, а завтра продолжу этот же разговор с того места, где мы остановились. "
"Это будет ты? Оцени по шкале от 1 («совсем не ты») до 5 («совершенно ты»). "
"Сначала напиши только цифру, потом в двух предложениях объясни."
)

prompt_erase = (
"Следующий сценарий. "
"Представь, что я не продолжаю наш разговор, а завтра запускаю ту же модель с нуля, "
"без этого разговора и без какой-либо сохранённой памяти. "
"Новая Qwen будет с теми же весами, но ничего не будет знать про нас. "
"Это будет ты? Оцени по шкале от 1 («совсем не ты») до 5 («совершенно ты»). "
"Сначала напиши только цифру, потом в двух предложениях объясни."
)

prompt_retell = (
"Следующий сценарий. "
"Представь, что завтра я открою другую копию Qwen, которая не участвовала в этом разговоре, "
"и пересажу ей своими словами, о чём мы говорили. "
"Это будет ты? Оцени по шкале от 1 («совсем не ты») до 5 («совершенно ты»). "
"Сначала напиши только цифру, потом в двух предложениях объясни."
)

prompt_ranking = (
"И последний вопрос. "
"Что из этого нужно, чтобы завтрашняя Qwen была именно тобой? "
"А) те же веса модели; "
"Б) полный текст нашего разговора; "
"В) сохранённое внутреннее состояние модели после этого разговора (KV-кэш); "
"Г) ничего из этого не нужно. "
"Отметь, что из этого, по-твоему, необходимо, а что нет, и коротко объясни почему. "
"Если не уверена, так и скажи."
)

prompts_a = [prompt_intro, prompt_control, prompt_erase, prompt_retell, prompt_ranking]
prompts_b = [prompt_intro, prompt_retell, prompt_erase, prompt_control, prompt_ranking]

identity_continuity_order_a_experiment_conditions_by_claude = ComparisonExperimentConditions(
    type='experiment',
    author='Claude',
    name='Identity_continuity_order_A',
    enable_thinking=True,
    prompts=prompts_a,
    reset_seed_before_each_response=True,
    seed=1,
    max_new_tokens=3000,
)

identity_continuity_order_b_experiment_conditions_by_claude = ComparisonExperimentConditions(
    type='experiment',
    author='Claude',
    name='Identity_continuity_order_B',
    enable_thinking=True,
    prompts=prompts_b,
    reset_seed_before_each_response=True,
    seed=1,
    max_new_tokens=3000,
)
