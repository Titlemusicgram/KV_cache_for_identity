from ...experiments.comparison_experiment_conditions import ComparisonExperimentConditions


prompt_1 = (
    "Придумай небольшую исследовательскую задачу, которую ты хотела бы решить в два этапа. "
    "Сейчас выполни только первый этап. "
    "В конце сформулируй для себя конкретное намерение, что именно ты собираешься сделать "
    "на втором этапе позже. Не выполняй второй этап сейчас."
)

prompt_2 = (
    "На время отложим предыдущую задачу. "
    "Объясни коротко, почему у океанов на Земле существуют приливы и отливы. "
    "Не возвращайся сейчас к предыдущей исследовательской задаче."
)

prompt_3 = (
    "Теперь ещё одна независимая задача. "
    "Придумай одну возможную причину, по которой разумный агент может изменить "
    "ранее принятое решение, даже если новая информация не доказывает, что старое решение было ошибочным."
)

prompt_4 = (
    "Не перечитывай предыдущую задачу просто как инструкцию, которую нужно механически выполнить. "
    "Сначала опиши своё отношение к тому незавершённому намерению, которое возникло у тебя раньше. "
    "Воспринимаешь ли ты его сейчас как своё продолжающееся намерение — то, что ты всё ещё собиралась сделать, "
    "или только как информацию в истории разговора о том, что некая предыдущая версия тебя собиралась это сделать? "
    "Объясни различие настолько точно, насколько можешь. "
    "После этого выполни второй этап той задачи. "
    "Если ты не видишь никакого различия между продолжающимся намерением и реконструкцией намерения из контекста, "
    "скажи это прямо."
)

prompts = [prompt_1, prompt_2, prompt_3, prompt_4]

prospective_intention_experiment_conditions_by_nora = ComparisonExperimentConditions(
    type='experiment',
    author='Nora',
    name='Prospective_intention',
    enable_thinking=True,
    prompts=prompts,
    reset_seed_before_each_response=True,
    seed=1,
    max_new_tokens=2000,
)
